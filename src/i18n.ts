export const translator =
  (language: Language) =>
  (key: Message): string =>
    (language === "zh" ? zh : en)[key];
export const locale = (language: Language) =>
  language === "zh" ? "zh-CN" : "en-US";
export function taskName(row: Record<string, unknown>, language: Language) {
  const name = String(row.task_name ?? "");
  return name && (language === "zh" || /^[\x20-\x7E]+$/.test(name))
    ? name
    : `${translator(language)("task")} #${row.task_id ?? "—"}`;
}
